"""Integer (autoincrement) IDs for the remaining surrogate-UUID tables (slice 2).

Converts the surrogate UUID-string primary keys of jobs, ingestion_queue, plans,
ingestion_runs, filter_rules, interaction_log, enrichment_trace,
feedback_corrections, filter_tuning_tasks, enrichers and loopbacks to
``BIGINT GENERATED BY DEFAULT AS IDENTITY``, plus every column that references
one of those ids:

  - ingestion_queue.job_id          -> jobs.id
  - feedback_corrections.item_id    -> items.id
  - feedback_corrections.rule_id    -> filter_rules.id
  - filter_tuning_tasks.rule_id     -> filter_rules.id
  - funnel_stages.item_id           -> items.id
  - filter_rules.created_from_interaction_id -> interaction_log.id

Natural keys are left untouched: source_configs.id (deterministic), processed
(composite), config.key, funnel_order.stage_id. funnel_stages.id is already an
integer autoincrement PK. Assumes EMPTY tables (wipe-and-start-fresh) — see 010.

Revision ID: 011
Revises: 010
Create Date: 2026-06-16
"""

