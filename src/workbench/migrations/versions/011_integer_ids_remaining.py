def _to_identity_pk(table: str) -> None:
    op.execute(f"ALTER TABLE {table} DROP CONSTRAINT {table}_pkey")
    op.execute(f"ALTER TABLE {table} ALTER COLUMN id TYPE bigint USING id::bigint")
    op.execute(
        f"ALTER TABLE {table} ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY"
    )
    op.execute(f"ALTER TABLE {table} ADD PRIMARY KEY (id)")


def upgrade() -> None:
    for table in _IDENTITY_TABLES:
        _to_identity_pk(table)
    for table, col in _REF_COLS:
        op.execute(
            f"ALTER TABLE {table} ALTER COLUMN {col} TYPE bigint USING {col}::bigint"
        )


def _to_text_pk(table: str) -> None:
    op.execute(f"ALTER TABLE {table} DROP CONSTRAINT {table}_pkey")
    op.execute(f"ALTER TABLE {table} ALTER COLUMN id DROP IDENTITY IF EXISTS")
    op.execute(f"ALTER TABLE {table} ALTER COLUMN id TYPE text USING id::text")
    op.execute(f"ALTER TABLE {table} ADD PRIMARY KEY (id)")


def downgrade() -> None:
    for table, col in _REF_COLS:
        op.execute(
            f"ALTER TABLE {table} ALTER COLUMN {col} TYPE text USING {col}::text"
        )
    for table in _IDENTITY_TABLES:
        _to_text_pk(table)
