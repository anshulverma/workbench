"""Integer (autoincrement) IDs for items + triage_cards (slice 1).

Converts the surrogate UUID-string primary keys of ``items`` and ``triage_cards``
to ``BIGINT GENERATED BY DEFAULT AS IDENTITY``, and every column that references
an item id (``items.parent_item_id``, ``triage_cards.item_id``,
``interaction_log.item_id``, ``enrichment_trace.item_id``) to ``bigint``.

Assumes the affected tables are EMPTY at upgrade time (the project switched to
autoincrement ids with a wipe-and-start-fresh policy; there is no UUID->int
mapping to preserve). The ``USING col::bigint`` casts therefore never evaluate a
non-numeric UUID string. Natural keys (source_configs.id, processed, config.key,
funnel_stages.stage_id) are intentionally left untouched.

Revision ID: 010
Revises: 009
Create Date: 2026-06-16
"""

from alembic import op

revision = "010"
down_revision = "009"
branch_labels = None
depends_on = None


def _to_identity_pk(table: str) -> None:
    op.execute(f"ALTER TABLE {table} DROP CONSTRAINT {table}_pkey")
    op.execute(f"ALTER TABLE {table} ALTER COLUMN id TYPE bigint USING id::bigint")
    op.execute(
        f"ALTER TABLE {table} ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY"
    )
    op.execute(f"ALTER TABLE {table} ADD PRIMARY KEY (id)")


def _col_to_bigint(table: str, col: str) -> None:
    op.execute(
        f"ALTER TABLE {table} ALTER COLUMN {col} TYPE bigint USING {col}::bigint"
    )


def upgrade() -> None:
    _to_identity_pk("items")
    _col_to_bigint("items", "parent_item_id")

    _to_identity_pk("triage_cards")
    _col_to_bigint("triage_cards", "item_id")

    _col_to_bigint("interaction_log", "item_id")
    _col_to_bigint("enrichment_trace", "item_id")


def _to_text_pk(table: str) -> None:
    op.execute(f"ALTER TABLE {table} DROP CONSTRAINT {table}_pkey")
    op.execute(f"ALTER TABLE {table} ALTER COLUMN id DROP IDENTITY IF EXISTS")
    op.execute(f"ALTER TABLE {table} ALTER COLUMN id TYPE text USING id::text")
    op.execute(f"ALTER TABLE {table} ADD PRIMARY KEY (id)")


def downgrade() -> None:
    op.execute(
        "ALTER TABLE enrichment_trace ALTER COLUMN item_id TYPE text USING item_id::text"
    )
    op.execute(
        "ALTER TABLE interaction_log ALTER COLUMN item_id TYPE text USING item_id::text"
    )

    op.execute(
        "ALTER TABLE triage_cards ALTER COLUMN item_id TYPE text USING item_id::text"
    )
    _to_text_pk("triage_cards")

    op.execute(
        "ALTER TABLE items ALTER COLUMN parent_item_id TYPE text USING parent_item_id::text"
    )
    _to_text_pk("items")
